"""Execute generated ATNs using ANTLR's native Python simulators.

Direct left recursion is rewritten to precedence rules by the frontend.
Strict parsing remains the default; recover=True enables native error recovery.
"""
import sys
from copy import deepcopy

from antlr4 import Lexer, Parser
from antlr4.ParserRuleContext import InterpreterRuleContext
from antlr4.PredictionContext import PredictionContextCache
from antlr4.Token import Token
from antlr4.atn.ATNState import (RuleStopState, StarLoopEntryState, LoopEndState,
                               PlusBlockStartState, StarLoopbackState)
from antlr4.atn.LexerATNSimulator import LexerATNSimulator
from antlr4.atn.ParserATNSimulator import ParserATNSimulator
from antlr4.atn.Transition import Transition
from antlr4.dfa.DFA import DFA
from antlr4.error.Errors import (NoViableAltException, RecognitionException,
                                FailedPredicateException, InputMismatchException)
from antlr4.error.ErrorStrategy import DefaultErrorStrategy

_ArgumentDefault = object()


class _ActionReturn(BaseException):
    def __init__(self, value):
        self.value = value
        self.owner = None


class StrictErrorStrategy(DefaultErrorStrategy):
    """Keep the prototype's SyntaxError API while permitting native strategies."""
    def sync(self, recognizer):
        pass

    def reportError(self, recognizer, error):
        if isinstance(error, NoViableAltException):
            expected = 'a viable alternative'
        elif isinstance(error, FailedPredicateException):
            expected = 'semantic predicate '+error.predicate
        else:
            expected = recognizer.getExpectedTokens().toString(
                recognizer.literalNames, recognizer.symbolicNames)
        recognizer._fail(expected)

    def recoverInline(self, recognizer):
        raise InputMismatchException(recognizer)


class RuleContext(InterpreterRuleContext):
    # The runtime's base interpreter context stores the index but inherits the
    # default getRuleIndex() == -1; expose it for native tree rendering.
    def getRuleIndex(self):
        return self.ruleIndex


class GeneratedLexer(Lexer):
    channelNames = ['DEFAULT_TOKEN_CHANNEL', 'HIDDEN']
    modeNames = ['DEFAULT_MODE']

    def __init__(self, input, output=sys.stdout, *, recover=False):
        super().__init__(input, output)
        self.recoverErrors = recover
        decisions = [DFA(state, index) for index, state in enumerate(self.atn.decisionToState)]
        self._interp = LexerATNSimulator(self, self.atn, decisions, PredictionContextCache())

    def notifyListeners(self, error):
        if self.recoverErrors:
            return super().notifyListeners(error)
        char = self._input.getText(self._tokenStartCharIndex, self._input.index)
        raise SyntaxError(f'Unexpected character {char!r} at '
                          f'{self._tokenStartLine}:{self._tokenStartColumn}') from error


class GeneratedParser(Parser):
    def _scope_execute(self, rule, kind, index, context, error=None):
        state = context._actionLocals
        session = state.get('_antlr_session')
        if session is None:
            session = self._scopeMethods[rule](self, context)
            state['_antlr_session'] = session
            next(session)
        success, result = session.send((kind, index, context, error))
        if not success:
            if isinstance(result, _ActionReturn):
                result.owner = state
            raise result
        return result

    def _run_hook(self, index, hook):
        if index in getattr(self, '_scopeMethods', {}):
            return self._scope_execute(index, hook, 0, self._ctx,
                                       sys.exc_info()[1] if hook == 'finally' else None)
        method = getattr(self, '_ruleHooks', {}).get(index, {}).get(hook)
        if method is not None:
            method(self, self._ctx)

    def _new_context(self, index, parent, invoking, arguments=None):
        # Fallback keeps recognizers generated by earlier alpha versions usable.
        if hasattr(self, '_contextTypes'):
            defaults = deepcopy(getattr(self, '_ruleArgumentDefaults', {}).get(index, {}))
            defaults.update(arguments or {})
            return self._contextTypes[index](self, parent, invoking, **defaults)
        return RuleContext(parent, invoking, index)

    def __init__(self, input, output=sys.stdout, *, recover=False):
        super().__init__(input, output)
        if not recover and type(self._errHandler) is DefaultErrorStrategy:
            self._errHandler = StrictErrorStrategy()
        decisions = [DFA(state, index) for index, state in enumerate(self.atn.decisionToState)]
        self._interp = ParserATNSimulator(self, self.atn, decisions, PredictionContextCache())

    def _fail(self, expected):
        token = self._input.LT(1)
        self._syntaxErrors += 1
        raise SyntaxError(f'Expected {expected}, got {token.text!r} at {token.line}:{token.column}')

    def _parse_rule(self, index, precedence=0, arguments=None):
        """Walk an ATN with adaptive prediction and native precedence contexts.

        Native contexts preserve rule invoking states, allowing prediction to
        look through returns into the caller. Rule invocation is iterative.
        """
        start = self.atn.ruleToStartState[index]
        parent, invoking = self._ctx, self.state
        precedence_depth = len(self._precedenceStack)
        frames = [[parent, invoking, index, 'init']]
        root = self._new_context(index, parent, invoking, arguments)
        last_token, last_rule, call_arguments = None, None, None
        skip_sync_entry = None
        last_finally_return = False

        def finish_frame():
            nonlocal last_finally_return
            last_finally_return = False
            frame = frames[-1]
            caller, call_state, rule, phase = frame[:4]
            result = self._ctx
            try:
                if phase not in ('entry', 'init', 'init-return', 'finally', 'exit'):
                    frame[3] = 'finally'
                    self._run_hook(rule, 'finally')
            except _ActionReturn as control:
                frame[4:] = [control.value]
                last_finally_return = True
            finally:
                frame[3] = 'exit'
                frames.pop()
                try:
                    if result.start is None:
                        if self.atn.ruleToStartState[rule].isPrecedenceRule:
                            self._precedenceStack.pop()
                    elif self.atn.ruleToStartState[rule].isPrecedenceRule:
                        self.unrollRecursionContexts(caller)
                    else:
                        self.exitRule()
                finally:
                    self._ctx = caller
                    self.state = call_state
            return frame[4] if len(frame) > 4 else result

        try:
            if start.isPrecedenceRule:
                self.enterRecursionRule(root, start.stateNumber, index, precedence)
            else:
                self.enterRule(root, start.stateNumber, index)
            while True:
                try:
                    frame = frames[-1]
                    if frame[3] == 'init':
                        self._run_hook(frame[2], 'init')
                        frame[3] = 'body'
                    state = self.atn.states[self.state]
                    for instruction in getattr(self, '_stateActions', {}).get(self.state, ()):
                        action, *data = instruction
                        if action == 'select':
                            old = self._ctx
                            context = self._altContextTypes[data[0]](self, old)
                            context.children = old.children
                            for child in context.children or ():
                                child.parentCtx = context
                            if hasattr(old, '_previousContext'):
                                context._previousContext = old._previousContext
                            if hasattr(old, '_deferredEnter'):
                                context._deferredEnter = old._deferredEnter
                            if self.atn.ruleToStartState[context.ruleIndex].isPrecedenceRule:
                                self._ctx = context
                            else:
                                self.enterOuterAlt(context, 1)
                        elif action in ('bind', 'left'):
                            field, many = data[:2]
                            value = (self._ctx._previousContext if action == 'left' else
                                     last_rule if data[2] else last_token)
                            if many:
                                getattr(self._ctx, field).append(value)
                            else:
                                setattr(self._ctx, field, value)
                        elif action == 'arguments':
                            call_arguments = (data[0](self._ctx) if callable(data[0]) else
                                              self._argumentMethods[data[0]](self, self._ctx))
                        elif action == 'capture':
                            setattr(self._ctx, data[0], self.getCurrentToken())
                        elif action == 'enter' and getattr(self._ctx, '_deferredEnter', False):
                            self._ctx._deferredEnter = False
                            if self._parseListeners is not None:
                                self.triggerEnterRuleEvent()
                    if isinstance(state, RuleStopState):
                        caller, call_state, rule, phase = frames[-1][:4]
                        result = self._ctx
                        if phase == 'body':
                            result.stop = self._input.LT(-1)
                            frames[-1][3] = 'after'
                            self._run_hook(rule, 'after')
                        result = finish_frame()
                        last_rule = result
                        if not frames:
                            return result
                        call = self.atn.states[self.state].transitions[0]
                        self.state = call.followState.stateNumber
                        continue
                    if isinstance(state, StarLoopbackState):
                        self._errHandler.sync(self)
                        skip_sync_entry = state.transitions[0].target.stateNumber
                    elif isinstance(state, PlusBlockStartState) or len(state.transitions) > 1:
                        if self.state != skip_sync_entry:
                            self._errHandler.sync(self)
                        skip_sync_entry = None
                    choice = 1
                    if len(state.transitions) > 1:
                        lookahead = getattr(self, '_decisionLookahead', {}).get(self.state)
                        if lookahead is not None:
                            alternatives, fallback = lookahead
                            token = self._input.LA(1)
                            choice = next((i+1 for i, tokens in enumerate(alternatives)
                                           if token in tokens), fallback)
                            if not choice:
                                raise NoViableAltException(self)
                        else:
                            choice = self._interp.adaptivePredict(self._input, state.decision, self._ctx)
                    edge = state.transitions[choice-1]
                    kind = edge.serializationType
                    if kind == Transition.RULE:
                        frames.append([self._ctx, self.state, edge.ruleIndex, 'entry'])
                        names = getattr(self, '_ruleArgumentNames', [[] for _ in self.ruleNames])[edge.ruleIndex]
                        values = dict(zip(names, call_arguments or []))
                        call_arguments = None
                        context = self._new_context(edge.ruleIndex, self._ctx, self.state, values)
                        if edge.target.isPrecedenceRule:
                            self.enterRecursionRule(context, edge.target.stateNumber,
                                                    edge.ruleIndex, edge.precedence)
                        else:
                            self.enterRule(context, edge.target.stateNumber, edge.ruleIndex)
                        frames[-1][3] = 'init'
                    else:
                        if (kind == Transition.EPSILON and isinstance(state, StarLoopEntryState)
                                and state.isPrecedenceDecision and not isinstance(edge.target, LoopEndState)):
                            caller, call_state, rule, _ = frames[-1][:4]
                            if self._parseListeners is not None:
                                self.triggerExitRuleEvent()
                            context = self._new_context(rule, caller, call_state)
                            context._previousContext = self._ctx
                            if hasattr(self._ctx, '_actionLocals'):
                                context._actionLocals = self._ctx._actionLocals
                            listeners = self._parseListeners
                            if getattr(self, '_deferRecursionEnter', False):
                                self._parseListeners = None
                                context._deferredEnter = True
                            try:
                                self.pushNewRecursionContext(context,
                                                             self.atn.ruleToStartState[rule].stateNumber, rule)
                            finally:
                                self._parseListeners = listeners
                        if kind == Transition.ATOM:
                            last_token = self.match(edge.label_)
                            if last_token.type == Token.EOF:
                                self._matchedEOF = True
                        elif kind in (Transition.SET, Transition.NOT_SET):
                            last_token = self.getCurrentToken()
                            if not edge.matches(last_token.type, Token.MIN_USER_TOKEN_TYPE, self.atn.maxTokenType):
                                last_token = self._errHandler.recoverInline(self)
                            else:
                                self._errHandler.reportMatch(self)
                                self.consume()
                        elif kind == Transition.WILDCARD:
                            last_token = self.matchWildcard()
                        elif kind == Transition.PRECEDENCE:
                            if not self.precpred(self._ctx, edge.precedence):
                                raise FailedPredicateException(self, f'precedence >= {edge.precedence}')
                        elif kind == Transition.PREDICATE:
                            if not self.sempred(self._ctx, edge.ruleIndex, edge.predIndex):
                                text = getattr(self, '_predicateTexts', {}).get(edge.predIndex, str(edge.predIndex))
                                failure = getattr(self, '_predicateFailures', {}).get(edge.predIndex)
                                message = failure(self, self._ctx) if failure is not None else None
                                raise FailedPredicateException(self, text, message)
                        elif kind == Transition.ACTION:
                            self.action(self._ctx, edge.ruleIndex, edge.actionIndex)
                        elif kind != Transition.EPSILON:
                            raise RuntimeError(f'Unsupported parser transition: {kind}')
                        self.state = edge.target.stateNumber
                except BaseException as error:
                    pending = error
                    while frames:
                        frame = frames[-1]
                        rule = frame[2]
                        if isinstance(pending, _ActionReturn) and pending.owner is self._ctx._actionLocals:
                            frame[4:] = [pending.value]
                            frame[3] = 'init-return' if frame[3] == 'init' else 'returned'
                            self.state = self.atn.ruleToStopState[rule].stateNumber
                            pending = None
                            break
                        if frame[3] in ('body', 'after'):
                            frame[3] = 'catch'
                            try:
                                method = getattr(self, '_ruleCatches', {}).get(rule)
                                if method is not None:
                                    handled = method(self, self._ctx, pending)
                                elif isinstance(pending, RecognitionException):
                                    self._ctx.exception = pending
                                    self._errHandler.reportError(self, pending)
                                    self._errHandler.recover(self, pending)
                                    handled = True
                                else:
                                    handled = False
                                if handled:
                                    frame[3] = 'caught'
                                    self.state = self.atn.ruleToStopState[rule].stateNumber
                                    call_arguments = None
                                    pending = None
                                    break
                            except BaseException as replacement:
                                pending = replacement
                                if isinstance(pending, _ActionReturn):
                                    frame[4:] = [pending.value]
                                    frame[3] = 'returned'
                                    self.state = self.atn.ruleToStopState[rule].stateNumber
                                    pending = None
                                    break
                        try:
                            # Keep the pending exception active for a bare raise
                            # inside a user finally clause, including when a
                            # catch handler replaced the original exception.
                            try:
                                raise pending
                            except BaseException:
                                completed = finish_frame()
                            if last_finally_return:
                                if not frames:
                                    return completed
                                last_rule = completed
                                call = self.atn.states[self.state].transitions[0]
                                self.state = call.followState.stateNumber
                                pending = None
                                break
                        except BaseException as replacement:
                            pending = replacement
                    if pending is not None:
                        raise pending
        finally:
            try:
                while frames and self._ctx is not parent:
                    finish_frame()
            finally:
                self._ctx = parent
                self.state = invoking
                del self._precedenceStack[precedence_depth:]
