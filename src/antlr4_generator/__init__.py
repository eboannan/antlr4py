"""Experimental Python-only ANTLR grammar generator."""
from pathlib import Path

from .grammar import GrammarError, lexer_literal
from .composition import load_grammar, vocabulary_text
from .atn import build_atns, serialize_atn, decision_lookahead
from .tree_api import context_source, visitor_source, listener_source
from .actions import methods
from .naming import escaped

__all__ = ['generate', 'GrammarError']
__version__ = '0.11.0a1'


def generate(grammar_file, output_dir='.', *, overwrite=False, library_dirs=(),
             visitor=False, listener=True, encoding='utf-8', options=None, package=None):
    """Generate Python modules and .tokens sidecars, resolving grammar delegates.

    Return recognizer module paths only; helper modules and vocabularies are sidecars.
    Existing modules and sidecars are protected unless overwrite=True. Libraries
    are searched for imports and tokenVocab files; dependencies are never generated
    implicitly. Generate the lexer first when a parser needs its vocabulary.
    """
    path, output = Path(grammar_file), Path(output_dir)
    grammar = load_grammar(path, output, library_dirs, encoding=encoding, options=options)
    annotations = {}
    lexer_atn, parser_atn = build_atns(grammar, annotations)
    max_type = max([0, *grammar.tokens.values(), *grammar.literals.values()])
    token_names, literal_names = ['<INVALID>'] * (max_type+1), ['<INVALID>'] * (max_type+1)
    for name, token in grammar.tokens.items():
        if token_names[token] == '<INVALID>':
            token_names[token] = name
    for text, token in grammar.literals.items():
        literal_names[token] = repr(text)
    for rule in grammar.lexer:
        text = lexer_literal(rule.node)
        if rule.token_type and text is not None:
            literal_names[rule.token_type] = repr(text)
    while len(literal_names) > 1 and literal_names[-1] == '<INVALID>':
        literal_names.pop()
    metadata = (f'    grammarFileName = {path.name!r}\n'
                f'    symbolicNames = {token_names!r}\n'
                f'    literalNames = {literal_names!r}\n')
    constants = '    EOF = -1\n' + ''.join(f'    {escaped(name)} = {value}\n' for name, value in grammar.tokens.items())

    def preamble(base, atn):
        target = 'lexer' if base == 'GeneratedLexer' else 'parser'
        return ('# Generated by the experimental Python-only ANTLR generator.\n'
                'from antlr4 import *\n'
                'from antlr4.atn.ATNDeserializer import ATNDeserializer\n'
                'from antlr4.error.Errors import RecognitionException, NoViableAltException, InputMismatchException, FailedPredicateException\n'
                f'from antlr4_generator.runtime import {base}, _ActionReturn, _ArgumentDefault\n\n'
                f'def serializedATN():\n    return {serialize_atn(atn)!r}\n\n' +
                grammar.named_actions.get((target, 'header'), '')+'\n\n')

    def superclass(target):
        name = grammar.options.get('superClass')
        if not name or grammar.kind == 'combined' and target == 'lexer' or name in ('Parser', 'Lexer'):
            return '', ''
        module, _, symbol = name.rpartition('.')
        module = module or symbol
        return (f'if {symbol!r} not in globals():\n'
                f'    if __package__:\n        from .{module} import {symbol}\n'
                f'    else:\n        from {module} import {symbol}\n\n', ', '+symbol)

    modules = {}
    sidecars = {output / f'{grammar.name}.tokens': vocabulary_text(grammar)}
    if package:
        if not all(part.isidentifier() for part in package.split('.')):
            raise GrammarError('Package must be a dotted Python name')
        marker = output / '__init__.py'
        if not marker.exists():
            sidecars[marker] = '# Generated Python recognizer package.\n'
    if lexer_atn is not None:
        lexer_name = grammar.name if grammar.kind == 'lexer' else grammar.name+'Lexer'
        lexer_constants = ''.join(f'    {escaped(n)} = {i}\n' for i, n in enumerate(grammar.modes) if i)
        lexer_constants += ''.join(f'    {escaped(n)} = {i}\n' for n, i in grammar.channels.items() if i > 1)
        imports, parent = superclass('lexer')
        modules[output / f'{lexer_name}.py'] = (
            preamble('GeneratedLexer', lexer_atn) + imports +
            f'class {lexer_name}(GeneratedLexer{parent}):\n' + metadata + constants + lexer_constants +
            f'    ruleNames = {[r.name for r in grammar.lexer]!r}\n'
            f'    modeNames = {grammar.modes!r}\n'
            f'    channelNames = {list(grammar.channels)!r}\n'
            '    atn = ATNDeserializer().deserialize(serializedATN())\n'+methods(grammar, 'lexer'))
        if grammar.kind == 'combined':
            sidecars[output / f'{lexer_name}.tokens'] = vocabulary_text(grammar)
    if parser_atn is not None:
        parser_name = grammar.name if grammar.kind == 'parser' else grammar.name+'Parser'
        imports, parent = superclass('parser')
        context = grammar.options.get('contextSuperClass')
        if context and context != 'ParserRuleContext':
            context_base = (f'class _GeneratedRuleContext({context}):\n'
                            '    def __init__(self, parent, invokingState, ruleIndex):\n'
                            '        super().__init__(parent, invokingState)\n'
                            '        self.ruleIndex = ruleIndex\n'
                            '    def getRuleIndex(self):\n        return self.ruleIndex\n\n')
        else:
            context_base = 'from antlr4_generator.runtime import RuleContext as _GeneratedRuleContext\n\n'
        parser = (preamble('GeneratedParser', parser_atn) + imports + context_base +
                  f'class {parser_name}(GeneratedParser{parent}):\n' + metadata + constants +
                  f'    _grammarOptions = {grammar.options!r}\n' +
                  f'    ruleNames = {list(grammar.rules)!r}\n'
                  '    atn = ATNDeserializer().deserialize(serializedATN())\n\n' +
                  context_source(grammar))
        parser += '    _stateActions = {\n'
        for state, instructions in annotations.items():
            rendered = []
            for instruction in instructions:
                rendered.append(repr(instruction))
            parser += f'        {state}: ['+', '.join(rendered)+'],\n'
        parser += '    }\n'
        parser += f'    _decisionLookahead = {decision_lookahead(parser_atn, annotations)!r}\n'
        for index, name in enumerate(grammar.rules):
            if name in grammar.left_recursive:
                parser += f'\n    def {escaped(name)}(self, _p=0):\n        return self._parse_rule({index}, _p)\n'
            else:
                args = grammar.attributes[name]['args']
                signature = ''.join(', '+escaped(n)+('=_ArgumentDefault' if v is not None else '') for n, v in args)
                values = '{'+', '.join(repr(escaped(n))+': '+escaped(n) for n, v in args if v is None)+'}'
                parser += (f'\n    def {escaped(name)}(self{signature}):\n'
                           f'        _arguments = {values}\n')
                for argument, default in args:
                    if default is not None:
                        argument = escaped(argument)
                        parser += (f'        if {argument} is not _ArgumentDefault:\n'
                                   f'            _arguments[{argument!r}] = {argument}\n')
                parser += f'        return self._parse_rule({index}, arguments=_arguments)\n'
        parser += methods(grammar, 'parser')
        modules[output / f'{parser_name}.py'] = parser
    recognizers = tuple(modules)
    if parser_atn is not None:
        if visitor:
            modules[output / f'{grammar.name}Visitor.py'] = visitor_source(grammar)
        if listener:
            modules[output / f'{grammar.name}Listener.py'] = listener_source(grammar)
    for target, source in modules.items():
        try:
            compile(source, str(target), 'exec')
        except SyntaxError as error:
            raise GrammarError(f'Invalid generated Python in {target.name}: {error.msg}') from error
    # Check all collisions before creating any output, including sidecars.
    artifacts = {**modules, **sidecars}
    for target in artifacts:
        if target.exists() and not overwrite:
            raise FileExistsError(f'{target} already exists; use overwrite=True or --overwrite')
    output.mkdir(parents=True, exist_ok=True)
    for target, source in artifacts.items():
        with target.open('w' if overwrite else 'x', encoding='utf-8') as stream:
            stream.write(source)
    return recognizers
